"""
youtube/shorts_qc.py tests - per-Short quality control.

Covers spec scenario 19 (Short QC) at the unit level; scenario 20 (one
Short QC failure blocks package approval) is covered at the orchestration
level in tests/test_shorts_engine.py and the Telegram-package level in
tests/test_shorts_telegram.py.

DURATION HARD-GATE PATCH (2026-09): a real production Short at 55.2s
(configured band: 30-50s) passed QC before this patch, because the only
pre-existing duration check ("video_duration_valid") only verified
`duration > 0` and never compared the real duration against
settings.SHORTS_TARGET_SECONDS_MIN/MAX at all. The tests below
(test_duration_below_minimum_fails_qc through
test_config_change_is_respected_by_duration_gate) cover the new
"duration_within_target_range" hard gate directly, including reproducing
the real 55.2s/30-50s scenario as a synthetic fixture (no real production
artifact is read, deleted, or regenerated by this file).
"""
from __future__ import annotations

from core.config import settings
from youtube import shorts_qc


def _valid_video_stream(w=1080, h=1920):
    return {"codec_type": "video", "width": w, "height": h}


def _valid_audio_stream():
    return {"codec_type": "audio"}


def _probe(w=1080, h=1920, duration=35.0):
    return {"format": {"duration": str(duration)}, "streams": [_valid_video_stream(w, h), _valid_audio_stream()]}


def test_run_short_quality_check_passes_for_a_valid_short(tmp_path, monkeypatch):
    from PIL import Image

    video = tmp_path / "short_01.mp4"
    video.write_bytes(b"x" * 100)
    thumb = tmp_path / "short_01.png"
    Image.new("RGB", (1080, 1920)).save(thumb)

    monkeypatch.setattr(shorts_qc, "_ffprobe_json", lambda path: _probe())

    report = shorts_qc.run_short_quality_check(
        video, thumb, narration="The signal was never explained.", title="The Unexplained Signal",
        source_text="The signal was never explained by any known source.",
    )
    assert report.passed, report.errors


def test_run_short_quality_check_fails_on_missing_video():
    report = shorts_qc.run_short_quality_check(
        __import__("pathlib").Path("/nonexistent/short.mp4"), __import__("pathlib").Path("/nonexistent/short.png"),
        narration="text", title="t", source_text="text",
    )
    assert not report.passed
    assert report.checks["video_file_exists"]["passed"] is False


def test_run_short_quality_check_fails_on_wrong_resolution(tmp_path, monkeypatch):
    from PIL import Image

    video = tmp_path / "short.mp4"
    video.write_bytes(b"x" * 100)
    thumb = tmp_path / "short.png"
    Image.new("RGB", (1080, 1920)).save(thumb)

    monkeypatch.setattr(shorts_qc, "_ffprobe_json", lambda path: _probe(w=1920, h=1080))  # wrong - landscape

    report = shorts_qc.run_short_quality_check(video, thumb, "narration text", "title", "narration text")
    assert not report.passed
    assert report.checks["resolution_1080x1920"]["passed"] is False
    assert report.checks["aspect_ratio_9_16"]["passed"] is False


def test_check_english_only_flags_non_latin_text():
    ok, _ = shorts_qc.check_english_only("This has Türkçe karakterler içeriyor.")
    assert ok is False
    ok2, _ = shorts_qc.check_english_only("This is plain English text.")
    assert ok2 is True


def test_check_no_leaked_markers_flags_debug_labels():
    ok, detail = shorts_qc.check_no_leaked_markers("Scene 01: a cinematic shot. DEBUG: testing.")
    assert ok is False
    ok2, _ = shorts_qc.check_no_leaked_markers("A perfectly normal narration sentence.")
