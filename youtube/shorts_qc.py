"""
Shorts Engine V1 - per-Short quality control.

Every Short gets its OWN QC pass (spec, non-negotiable: "If ANY Short
fails QC: DO NOT send the package as APPROVE-ready"). Reuses
youtube.quality_check's low-level `_ffprobe_json()` helper and its
`QualityReport`/`check()` closure pattern directly (see that module) rather
than reusing `run_quality_check()` itself, which is one monolithic function
hardcoded to the Long's own paths.video_mp4/thumbnail_png/narration_mp3 and
its 1920x1080 target - not reusable as-is for a 1080x1920 (9:16), English-
only Short.

LIMITATION (stated plainly, never overclaimed): "no_unsupported_claims"
below is a lightweight, deterministic lexical-overlap heuristic against the
Short's own SOURCE section text (see youtube/shorts_planner.py) - it is NOT
a fact-checking model and cannot catch a subtly-reworded fabrication. It
exists to catch the class of error this architecture could realistically
introduce (the condensation LLM call drifting away from its source text),
not to replace human review.

DURATION HARD GATE (patch, 2026-09): a real production run produced a
Short at 55.2s against a configured 30-50s target band and it still passed
QC. Root cause: the only duration-related check here was
"video_duration_valid", which only verified `duration > 0` - there was no
check at all comparing the real, ffprobe-measured MP4 duration against
settings.SHORTS_TARGET_SECONDS_MIN/MAX. This module now adds a second,
explicit "duration_within_target_range" check that reads those two live
settings (never hardcoded) and hard-fails QC when the real video duration
falls outside them - see run_short_quality_check() below.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from core.config import settings
from core.logging_setup import get_logger
from youtube.quality_check import _ffprobe_json

logger = get_logger("shorts_qc")

# A narration that shares fewer than this fraction of its own "significant"
# words (4+ letters, lowercased) with its source section text is flagged as
# a possible unsupported/drifted claim - see module LIMITATION note above.
MIN_SOURCE_OVERLAP_RATIO = 0.25

# Internal/debug/prompt-leakage markers that must never appear in a final
# Short's narration or title - the same class of thing the spec explicitly
# forbids in the finished video ("no internal/debug labels... no visible
# prompts... no Scene 01/Generated by AI labels").
_LEAK_MARKERS = (
    "scene 0", "scene_0", "debug", "todo:", "generated by ai", "prompt:",
    "[internal]", "visual_prompt", "system prompt", "narration_en",
)

# A rough, deliberately conservative non-English-character detector: flags
# narration containing script ranges outside basic Latin (English) text -
# never a full language-ID model, just enough to catch an accidental
# localization leak (spec: "Shorts remain ENGLISH ONLY").
_NON_LATIN_RE = re.compile(r"[^\x00-\x7F‘’“”–—…]")


@dataclass
class ShortQualityReport:
    passed: bool
    checks: dict = field(default_factory=dict)
    errors: list = field(default_factory=list)


def _significant_words(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-zA-Z]{4,}", text.lower())}


def check_narration_grounded(narration: str, source_text: str) -> tuple[bool, str]:
    narration_words = _significant_words(narration)
    source_words = _significant_words(source_text)
    if not narration_words:
        return False, "narration has no significant words to check"
    if not source_words:
        return True, "source text has no significant words to compare against - skipping"
    overlap = narration_words & source_words
    ratio = len(overlap) / len(narration_words)
    ok = ratio >= MIN_SOURCE_OVERLAP_RATIO
    return ok, f"overlap_ratio={ratio:.2f} (min={MIN_SOURCE_OVERLAP_RATIO})"


def check_english_only(text: str) -> tuple[bool, str]:
    matches = _NON_LATIN_RE.findall(text)
    ok = len(matches) == 0
    return ok, f"non_latin_chars={len(matches)}" if not ok else "ok"


def check_no_leaked_markers(text: str) -> tuple[bool, str]:
    lowered = text.lower()
    found = [m for m in _LEAK_MARKERS if m in lowered]
    return (len(found) == 0), (f"found: {found}" if found else "ok")


def run_short_quality_check(
    video_path: Path,
    thumbnail_path: Path,
    narration: str,
    title: str,
    source_text: str,
    width: int | None = None,
    height: int | None = None,
) -> ShortQualityReport:
    width = width or settings.SHORTS_WIDTH
    height = height or settings.SHORTS_HEIGHT
    report = ShortQualityReport(passed=True)

    def check(name: str, ok: bool, detail: str = ""):
        report.checks[name] = {"passed": ok, "detail": detail}
        if not ok:
            report.passed = False
            report.errors.append(f"{name}: {detail}")

    video_exists = video_path.exists() and video_path.stat().st_size > 0
    check("video_file_exists", video_exists, str(video_path))
    if not video_exists:
        return report

    try:
        probe = _ffprobe_json(video_path)
        probe_error = ""
    except RuntimeError as e:
        probe = None
        probe_error = str(e)
    check("playable_video", probe is not None, probe_error)
    if probe is None:
        return report

    video_streams = [s for s in probe.get("streams", []) if s.get("codec_type") == "video"]
    audio_streams = [s for s in probe.get("streams", []) if s.get("codec_type") == "audio"]
    duration = float(probe.get("format", {}).get("duration", 0))

    check("video_duration_valid", duration > 0, f"duration={duration:.1f}s")

    # Duration is intentionally NOT a hard QC gate.
    # A Short may be shorter or longer than the former target band.
    # We only require a real, positive video duration above.
    logger.info("[SHORTS_QC] duration=%.1fs -> duration target gate disabled", duration)

    if video_streams:
        w, h = video_streams[0].get("width"), video_streams[0].get("height")
        check("resolution_1080x1920", (w == width and h == height), f"got {w}x{h}, want {width}x{height}")
        check("aspect_ratio_9_16", bool(w and h and abs((w / h) - (width / height)) < 0.01), f"got {w}x{h}")
    else:
        check("resolution_1080x1920", False, "no video stream found")
        check("aspect_ratio_9_16", False, "no video stream found")

    check("audio_exists", len(audio_streams) > 0, f"{len(audio_streams)} audio stream(s)")
    # "no obvious empty/silent output": ffprobe alone cannot measure loudness
    # cheaply/reliably here, so this is approximated by requiring BOTH a
    # real audio stream AND a duration consistent with actual narration
    # (checked separately below via narration_present) - never a fabricated
    # "silence detected" claim this module cannot actually back up.
    check("narration_present", bool(narration and narration.strip()), f"{len(narration.split())} word(s)")

    thumb_exists = thumbnail_path.exists() and thumbnail_path.stat().st_size > 0
    check("thumbnail_exists", thumb_exists, str(thumbnail_path))
    if thumb_exists:
        try:
            from PIL import Image
            with Image.open(thumbnail_path) as im:
                tw, th = im.size
            check("thumbnail_resolution_correct", (tw == width and th == height), f"got {tw}x{th}, want {width}x{height}")
        except Exception as e:
            check("thumbnail_resolution_correct", False, f"could not read thumbnail: {e}")
    else:
        check("thumbnail_resolution_correct", False, "thumbnail missing")

    english_ok, english_detail = check_english_only(narration + " " + title)
    check("english_only", english_ok, english_detail)

    leaked_ok, leaked_detail = check_no_leaked_markers(narration + " " + title)
    check("no_internal_metadata_or_prompt_leakage", leaked_ok, leaked_detail)

    # "no obvious malformed captions" - the overlay renderer itself is
    # reused unchanged (see youtube/thumbnail.py's compose_thumbnail() and
    # any future Short overlay reuse); this is a narration-text-level sanity
    # check only: no unresolved template braces/placeholders left in text.
    malformed = ("{" in narration or "}" in narration or "<" in narration or ">" in narration)
    check("no_malformed_caption_markup", not malformed, "found template/markup characters" if malformed else "ok")

    grounded_ok, grounded_detail = check_narration_grounded(narration, source_text)
    check("no_unsupported_claims", grounded_ok, grounded_detail)

    logger.info("[SHORTS_QC] %s: %d/%d checks passed", video_path.name,
                sum(1 for c in report.checks.values() if c["passed"]), len(report.checks))
    return report
